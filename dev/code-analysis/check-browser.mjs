import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { createServer } from 'vite';

// Standalone contributor-tool check; no application backend or Docker required.
const vite = await createServer({ configFile: fileURLToPath(new URL('vite.config.js', import.meta.url)),
    server: { host: '127.0.0.1', port: 0, strictPort: false } });
let browser;
try {
    await vite.listen();
    browser = await chromium.launch({
        ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}),
    });
    const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
    page.setDefaultTimeout(10000);
    const errors = [], apiCalls = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiCalls.push(request.url()); });
    const origin = vite.resolvedUrls.local[0];
    await page.goto(origin);
    await page.getByRole('heading', { name: 'Code relationships' }).waitFor();
    const modules = page.getByRole('navigation', { name: 'Modules' });
    await page.getByLabel('Application', { exact: true }).selectOption('backend');
    await page.getByRole('searchbox', { name: 'Find a module' }).fill('notifications.js');
    assert.equal(await modules.getByRole('link').count(), 2);
    await modules.getByRole('link', { name: 'backend/notifications.js', exact: true }).click();
    await page.getByRole('heading', { name: 'backend/notifications.js', exact: true }).waitFor();
    await page.getByLabel('Relationships', { exact: true }).selectOption('dynamic');
    await page.getByRole('cell', { name: 'dynamic-import', exact: true }).first().waitFor();
    assert.ok(await page.locator('.edge.dynamic').count() > 0);
    await page.getByLabel('Relationships', { exact: true }).selectOption('static');
    assert.equal(await page.locator('.edge.dynamic').count(), 0);
    assert.equal(await page.getByRole('cell', { name: 'dynamic-import', exact: true }).count(), 0);
    await page.getByLabel('Relationships', { exact: true }).selectOption('all');
    await page.getByRole('searchbox').fill('');
    await page.getByLabel('Application', { exact: true }).selectOption('frontend');
    await modules.getByRole('link', { name: 'frontend/i18n/index.js', exact: true }).click();
    await page.getByRole('heading', { name: 'frontend/i18n/index.js', exact: true }).waitFor();
    assert.ok(await page.getByRole('cell', { name: 'glob-lazy', exact: true }).count() > 0);
    await page.goto(origin + '#module=' + encodeURIComponent('src/frontend/src/lib/caddyfileMode.js'));
    await page.getByText('Generated by src/frontend/scripts/fetch-caddyfile-mode.mjs;', { exact: false }).waitFor();
    await page.goto(origin + '#module=' + encodeURIComponent('not-in-snapshot'));
    await page.getByRole('alert').filter({ hasText: 'not in the snapshot' }).waitFor();
    await page.goto(origin);
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download snapshot' }).click();
    assert.match((await downloaded).suggestedFilename(), /^caddy-ui-analysis-.*\.json$/);
    if (process.env.ANALYSIS_SCREENSHOT) await page.screenshot({ path: process.env.ANALYSIS_SCREENSHOT, fullPage: true });
    assert.deepEqual(errors, []);
    assert.deepEqual(apiCalls, []);
    console.log('Dependency explorer browser checks passed.');
} finally {
    await browser?.close();
    await vite.close();
}
