import { readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { cruise } from 'dependency-cruiser';
import picomatch from 'picomatch';
import { sourceReferences } from './source.mjs';
import { dynamicKinds, findCycles, folderMatrix } from './model.js';

export const scopes = ['src/backend/src', 'src/frontend/src'];
const generated = 'src/frontend/src/lib/caddyfileMode.js';
const generatedReason = 'Generated by src/frontend/scripts/fetch-caddyfile-mode.mjs; excluded even when present locally.';
const javascript = /\.(?:[cm]?js|jsx)$/;
const posix = file => file.replaceAll('\\', '/');

function group(file) {
    const parts = file.split('/');
    return [parts[1], ...parts.slice(3, -1)].join('/');
}

export async function analyzeRepository(root) {
    const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trimEnd();
    const tracked = git(['ls-files', '-z']).split('\0').filter(file => scopes.some(scope => file.startsWith(scope + '/'))).filter(Boolean).sort();
    const files = tracked.filter(file => javascript.test(file) && file !== generated);
    if (!files.length) throw new Error('No tracked application JavaScript found. Run from a caddy-ui checkout.');
    const sources = new Map(await Promise.all(files.map(async file => [file, await readFile(path.join(root, file), 'utf8')])));
    // Every tracked source is an entry. Resolve direct dependencies but never
    // traverse them: an untracked/generated file must not change the scope.
    const result = await cruise(files, { baseDir: root, outputType: 'json', doNotFollow: { path: '.' } },
    { extensions: ['.js', '.jsx', '.mjs', '.cjs', '.json'], conditionNames: ['import', 'node', 'default'] });
    const output = typeof result.output === 'string' ? JSON.parse(result.output) : result.output;
    const modules = new Map(output.modules.map(module => [posix(module.source), module]));
    const nodes = new Map(files.map(file => [file, { id: file, label: file, kind: 'source', group: group(file) }]));
    const edges = [], diagnostics = [];
    function addEdge(from, target, reference, specifier = reference.specifier) {
        nodes.set(target.id, nodes.get(target.id) || target);
        edges.push({ from, to: target.id, kind: reference.kind, specifier,
            line: reference.line, column: reference.column, excerpt: reference.excerpt });
    }
    function targetFor(from, dependency) {
        const specifier = dependency.module, resolved = posix(dependency.resolved || '');
        const relative = specifier.startsWith('.') || specifier.startsWith('/');
        const expected = relative ? path.posix.normalize(path.posix.join(path.posix.dirname(from), specifier)) : '';
        if (expected === generated || resolved === generated) return { id: generated, label: generated, kind: 'generated', group: 'generated', reason: generatedReason };
        if (dependency.coreModule) return { id: 'node:' + specifier.replace(/^node:/, ''), label: specifier, kind: 'builtin', group: 'Node.js' };
        if (!relative) return { id: 'package:' + specifier, label: specifier, kind: 'package', group: 'Packages', unresolved: dependency.couldNotResolve };
        if (dependency.couldNotResolve) return { id: `unresolved:${from}:${specifier}`, label: specifier, kind: 'unresolved', group: 'Unresolved' };
        if (nodes.has(resolved)) return nodes.get(resolved);
        return { id: resolved, label: resolved, kind: javascript.test(resolved) ? 'out-of-scope' : 'asset', group: 'Other files' };
    }
    for (const [file, source] of sources) {
        const dependencies = modules.get(file)?.dependencies;
        if (!dependencies) throw new Error(`Dependency-cruiser did not analyze ${file}`);
        const references = sourceReferences(source, file);
        for (const reference of references) {
            if (reference.kind.startsWith('glob-')) {
                if (reference.unsupportedOptions || !reference.patterns.every(pattern => typeof pattern === 'string' && /^(?:!?\.\.?\/|!?\/)/.test(pattern))) {
                    diagnostics.push({ file, line: reference.line, message: 'Unsupported glob: use literal relative or root-relative patterns and literal options without base. Aliases and expressions are not expanded.' });
                    continue;
                }
                const normalize = pattern => pattern.startsWith('/')
                    ? path.posix.join('src', file.split('/')[1], pattern.slice(1))
                    : path.posix.join(path.posix.dirname(file), pattern);
                const positive = reference.patterns.filter(pattern => !pattern.startsWith('!')).map(normalize);
                const negative = reference.patterns.filter(pattern => pattern.startsWith('!')).map(pattern => normalize(pattern.slice(1)));
                const matches = tracked.filter(candidate => positive.some(pattern => picomatch(pattern, { dot: true })(candidate))
                    && !negative.some(pattern => picomatch(pattern, { dot: true })(candidate)));
                for (const candidate of matches) addEdge(file, nodes.get(candidate) || { id: candidate, label: candidate, kind: 'asset', group: 'Other files' }, reference, reference.patterns.join(', '));
                if (!matches.length) diagnostics.push({ file, line: reference.line, message: 'Glob has no tracked matches in the application scope.' });
                continue;
            }
            if (reference.specifier === null) {
                diagnostics.push({ file, line: reference.line, message: `Nonliteral ${reference.kind}: target is unknown.`, excerpt: reference.excerpt });
                continue;
            }
            const matchesReference = dependency => dependency.module === reference.specifier
                || `${dependency.protocol || ''}${dependency.module}` === reference.specifier;
            const dependency = dependencies.find(matchesReference);
            if (!dependency) {
                diagnostics.push({ file, line: reference.line, message: `Dependency-cruiser could not extract ${reference.specifier}.`, excerpt: reference.excerpt });
                addEdge(file, { id: `unresolved:${file}:${reference.specifier}`, label: reference.specifier, kind: 'unresolved', group: 'Unresolved' }, reference);
                continue;
            }
            const target = targetFor(file, dependency);
            addEdge(file, target, reference);
            if (target.kind === 'unresolved' || target.unresolved) diagnostics.push({ file, line: reference.line,
                message: `Cannot resolve ${reference.specifier}${target.kind === 'package' ? '; install the owning package dependencies' : ''}.` });
        }
        for (const dependency of dependencies) {
            if (!references.some(reference => reference.specifier === dependency.module || reference.specifier === `${dependency.protocol || ''}${dependency.module}`)) {
                addEdge(file, targetFor(file, dependency), { kind: dependency.dynamic ? 'dynamic-import' : dependency.moduleSystem === 'cjs' ? 'require' : 'import',
                    specifier: dependency.module, line: null, column: null, excerpt: '' });
                diagnostics.push({ file, line: null, message: `No source location available for ${dependency.module}.` });
            }
        }
    }
    const nodeList = [...nodes.keys()].sort().map(id => nodes.get(id));
    edges.sort((a, b) => a.from.localeCompare(b.from, 'en') || (a.line || 0) - (b.line || 0) || a.to.localeCompare(b.to, 'en') || a.kind.localeCompare(b.kind, 'en'));
    const fingerprint = createHash('sha256');
    fingerprint.update(JSON.stringify(tracked) + '\0');
    for (const [file, source] of sources) fingerprint.update(file + '\0' + source + '\0');
    const toolPackage = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
    return { schemaVersion: 1, metadata: { commit: git(['rev-parse', 'HEAD']),
        dirty: Boolean(git(['status', '--porcelain', '--untracked-files=no', '--', ...scopes])), sourceHash: fingerprint.digest('hex'), scopes,
        tools: Object.fromEntries(['dependency-cruiser', '@babel/parser', 'picomatch'].map(name => [name, toolPackage.devDependencies[name]])),
        limitations: ['Static module relationships, not a runtime call graph or proof of reachability.',
            'Application source only; tests, build tools and package internals are outside the scope.',
            'Vite globs expand tracked application files only. Computed imports, aliases and custom loaders may remain unresolved.',
            'Generated editor mode is represented but never analyzed. No application modules are executed.'] },
        nodes: nodeList, edges, diagnostics,
        cycles: findCycles(nodeList, edges), staticCycles: findCycles(nodeList, edges.filter(edge => !dynamicKinds.includes(edge.kind))),
        matrix: folderMatrix(nodeList, edges) };
}
